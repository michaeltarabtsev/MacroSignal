def score_zeroshot(text: str) -> float:
    """
    Classifies text directly into hawkish / dovish / neutral using
    natural language inference — no keywords required.

    Returns a score in [-1, +1]:
      +1 = fully hawkish, -1 = fully dovish, 0 = neutral
    """
    # bart-large-mnli has a 1024 token limit — truncate long texts
    truncated = text[:2000]
    result    = zeroshot(truncated, ZEROSHOT_LABELS, multi_label=False)

    scores = {label: score for label, score in
              zip(result["labels"], result["scores"])}

    hawk_prob = scores.get("hawkish monetary policy tightening", 0)
    dove_prob = scores.get("dovish monetary policy easing", 0)
    return float(hawk_prob - dove_prob)   # positive = hawkish, negative = dovish

