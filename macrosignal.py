def get_live_price(ticker: str, fallback: float) -> float:
    """
    Fetches the latest available close price.
    Tries progressively longer periods to handle weekends, holidays,
    and futures contracts that need more history to return data.
    Falls back to entry price if the ticker is truly unavailable.
    """
    for period in ("1d", "5d", "1mo"):
        try:
            hist = yf.Ticker(ticker).history(period=period)
            if not hist.empty and "Close" in hist.columns:
                closes = hist["Close"].dropna()
                if not closes.empty:
                    return round(float(closes.iloc[-1]), 2)
        except Exception:
            pass
    return fallback

def time_open(timestamp_str: str) -> str:
    try:
        opened = datetime.datetime.strptime(timestamp_str, "%Y-%m-%d %H:%M:%S")
        delta  = datetime.datetime.now() - opened
        hours  = int(delta.total_seconds() // 3600)
        if hours < 1:   return f"{int(delta.total_seconds() // 60)}m"
        elif hours < 24: return f"{hours}h"
        else:            return f"{delta.days}d {hours % 24}h"
    except Exception:
        return "—"

def calc_pnl(entry: float, live: float, notional: float, direction: str) -> tuple:
    """
    Returns (current_value, pnl_usd, pnl_pct) for a position.

    LONG:
      units = notional / entry
      current_value = units * live
      pnl_pct = (live - entry) / entry * 100

    SHORT:
      We effectively borrowed and sold at entry, buying back at live.
      pnl_pct = (entry - live) / entry * 100
      current_value = notional * (1 + pnl_pct/100)
      Capped at -100% loss (current_value floored at 0).
    """
    units = notional / entry
    if direction == "LONG":
        current_val = units * live
        pnl_pct     = ((live - entry) / entry) * 100
    else:
        pnl_pct     = ((entry - live) / entry) * 100
        pnl_pct     = max(pnl_pct, -100.0)   # can't lose more than 100%
        current_val = max(notional * (1 + pnl_pct / 100), 0.0)

    pnl_usd = current_val - notional
    return round(current_val, 2), round(pnl_usd, 2), round(pnl_pct, 2)

def stop_distance(entry: float, live: float, direction: str) -> tuple:
    """
    Distance from current price to the 3% stop loss.
    Returns (distance_pct, near_stop).
    Positive = safe, negative = stop already breached.
    """
    stop = entry * 0.97 if direction == "LONG" else entry * 1.03
    dist = ((live - stop) / live * 100) if direction == "LONG" else ((stop - live) / live * 100)
    return round(dist, 2), dist < 1.0

