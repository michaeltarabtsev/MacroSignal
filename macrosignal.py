# ── Position sizing ────────────────────────────────────────────────────────────
def calculate_position_size(ticker: str, confidence: float) -> tuple:
    """
    Volatility-scaled position sizing.
    Target: each position contributes 1% daily volatility to the portfolio.
    Scaled further by model confidence. Capped at 25%, floored at 5%.
    """
    try:
        hist     = yf.Ticker(ticker).history(period="1mo")["Close"]
        daily_vol = hist.pct_change().dropna().std()
        raw_weight = 0.01 / daily_vol if daily_vol > 0 else 0.15
    except Exception:
        raw_weight = 0.15

    confidence_scalar = (confidence - CONFIDENCE_FLOOR) / (1 - CONFIDENCE_FLOOR)
    weight    = min(max(raw_weight * confidence_scalar, 0.05), 0.25)
    notional  = round(BASE_CAPITAL * weight, 2)
    friction  = round(notional * (FRICTION_BPS / 10_000), 2)
    return round(weight * 100, 1), notional, friction

