def compute_strategy_returns(df: pd.DataFrame) -> pd.Series:
    """
    Applies the threshold rule to compute per-event strategy returns.
    SHORT TLT on hawkish signal → strategy return = -TLT return (profit when TLT falls)
    LONG  TLT on dovish signal  → strategy return = +TLT return (profit when TLT rises)
    FLAT on neutral             → 0
    """
    rets = []
    for _, row in df.iterrows():
        if np.isnan(row["tlt_1d"]):
            rets.append(np.nan)
        elif row["score"] > 0.05:
            rets.append(-row["tlt_1d"])   # SHORT TLT
        elif row["score"] < -0.05:
            rets.append(row["tlt_1d"])    # LONG TLT
        else:
            rets.append(0.0)              # FLAT
    return pd.Series(rets, index=df["date"])

# ── Analytics ──────────────────────────────────────────────────────────────────
def compute_hit_rate(df: pd.DataFrame) -> dict:
    active = df[(df["label"] != "NEUTRAL") & df["tlt_1d"].notna()].copy()
    if len(active) == 0:
        return {"hit_rate": np.nan, "n_trades": 0,
                "n_hawkish": 0, "n_dovish": 0, "n_neutral": 0}
    hits = sum(
        1 for _, row in active.iterrows()
        if (row["label"] == "HAWKISH" and row["tlt_1d"] < 0)
        or (row["label"] == "DOVISH"  and row["tlt_1d"] > 0)
    )
    return {
        "hit_rate":  hits / len(active),
        "n_trades":  len(active),
        "n_hawkish": int((active["label"] == "HAWKISH").sum()),
        "n_dovish":  int((active["label"] == "DOVISH").sum()),
        "n_neutral": int((df["label"] == "NEUTRAL").sum()),
    }

def compute_ic(df: pd.DataFrame) -> dict:
    valid = df[["score", "tlt_1d"]].dropna()
    if len(valid) < 3:
        return {"ic": np.nan, "p_value": np.nan}
    ic, p = pearsonr(valid["score"].values, -valid["tlt_1d"].values)
    return {"ic": round(float(ic), 4), "p_value": round(float(p), 4)}

def compute_sharpe(strategy_returns: pd.Series) -> float:
    r = strategy_returns.replace(0.0, np.nan).dropna()
    if len(r) < 2 or r.std() == 0:
        return np.nan
    # Annualise using √8 (8 FOMC meetings per year)
    return round(float((r.mean() / r.std()) * np.sqrt(8)), 2)

